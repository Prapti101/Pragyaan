"""AI Assistant: chat over uploaded documents and the ticket knowledge base."""

from __future__ import annotations

import sys
from pathlib import Path

import streamlit as st

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "app"))

import ui  # noqa: E402
from copilot.assistant import answer, clear_history, history  # noqa: E402
from copilot.config import DOC_SIM_THRESHOLD, SIM_THRESHOLD  # noqa: E402
from copilot.feedback import set_thumbs  # noqa: E402
from copilot.knowledge import list_documents  # noqa: E402
from copilot.llm import provider_name  # noqa: E402
from copilot.severity import routing_bucket  # noqa: E402

P = st.session_state["_pages"]
user = ui.require_role("employee", "analyst")
email = user["login_id"]  # chat history is kept per account
llm = provider_name()

ui.page_header("AI Assistant",
               "Ask in plain language. Answers come from your uploaded documents first, then from 9.5k resolved "
               "tickets, always with their sources. Questions nobody has answered yet go to the senior queue.")

EXAMPLES = [
    "I forgot my password and cannot log into my account",
    "How do I integrate SAP ERP with Git?",
    "Summarize this week's tickets",
]


def render(msg: dict) -> None:
    meta = msg.get("meta") or {}
    kind = meta.get("kind")
    if msg["role"] == "user":
        with st.chat_message("user", avatar=":material/person:"):
            st.markdown(msg["content"])
        return
    with st.chat_message("assistant", avatar=":material/auto_awesome:"):
        if kind == "documents":
            how = "Generated by " + meta["method"] if meta.get("method") not in (None, "retrieval") else \
                "Most relevant passage from your documents"
            st.markdown(f":green-badge[:material/description: From your documents] :gray[{how}]")
            st.markdown(ui.md_lines(msg["content"]) if meta.get("method") in (None, "retrieval") else msg["content"])
            with st.expander(f"Sources ({len(meta.get('doc_sources') or [])})"):
                for i, h in enumerate(meta.get("doc_sources") or [], start=1):
                    st.markdown(f"**[D{i}] {h['title']}** :gray[{h['collection']}, similarity {h['similarity']:.2f}]")
                    st.caption(ui.clip(h["text"], 600))
        elif kind == "resolved":
            how = f"Generated by {meta['method']}" if meta.get("method") not in (None, "retrieval") else \
                "Answer reused from the closest past ticket"
            st.markdown(f":green-badge[:material/check_circle: From past tickets] :gray[{how}, "
                        f"match {float(meta.get('confidence') or 0):.2f}]")
            st.markdown(msg["content"])
            with st.expander(f"Past tickets used ({len(meta.get('sources') or [])})"):
                for s in meta.get("sources") or []:
                    st.markdown(f"**Ticket {s['ticket_id']}** :gray[similarity {s['similarity']:.2f}]  \n{s['snippet'][:220]}")
        elif kind == "escalated":
            sev = meta.get("severity") or {}
            bucket = routing_bucket(float(sev.get("score") or 0))
            color, icon = ui.BUCKET_BADGE.get(bucket, ("gray", ""))
            st.markdown(f":orange-badge[:material/forward: Sent to the senior queue] :{color}-badge[{icon} {bucket}]")
            st.markdown(
                f"I couldn't find an answer in your documents or past tickets (best ticket match "
                f"{float(meta.get('confidence') or 0):.2f}, needs {SIM_THRESHOLD:.2f}), so I created escalation "
                f"**#{meta.get('escalation_id')}**. Once a senior answers it, ask again and you'll get their answer."
            )
            if sev.get("top_terms"):
                st.markdown("Priority signals: " + " ".join(f":gray-badge[{t}]" for t in sev["top_terms"]))
            if meta.get("related_docs"):
                with st.expander("Possibly related document passages"):
                    for h in meta["related_docs"]:
                        st.markdown(f"**{h['title']}** :gray[similarity {h['similarity']:.2f}]")
                        st.caption(ui.clip(h["text"], 400))
        elif kind == "summary":
            method = "Extractive summary: the most representative sentences, selected with TF-IDF" \
                if meta.get("method") == "extractive" else f"Summary generated by {meta.get('method')}"
            st.markdown(f":blue-badge[:material/summarize: {meta.get('title', 'Document')}] :gray[{method}]")
            if meta.get("summary"):
                st.markdown(meta["summary"])
            else:
                st.markdown("\n".join(f"- {s}" for s in meta.get("sentences") or []) or "_The document is too short to summarize._")
        else:
            st.markdown(msg["content"])
        iid = meta.get("interaction_id")
        if iid and kind in ("documents", "resolved"):
            fb = st.feedback("thumbs", key=f"fb-{msg['id']}")
            saved_key = f"fb-saved-{msg['id']}"
            if fb is not None and st.session_state.get(saved_key) != fb:
                set_thumbs(int(iid), "up" if fb == 1 else "down")
                st.session_state[saved_key] = fb
                st.toast("Feedback saved.")


chat_col, side = st.columns([2.3, 1], gap="large")

with side:
    with st.container(key="card-mode"):
        st.markdown("##### How answers are made")
        if llm:
            st.markdown(f":green-badge[:material/check: {llm}] connected. Answers are written from retrieved "
                        "passages and tickets, with citations.")
        else:
            st.markdown(":gray-badge[Retrieval mode] No language model is connected, so answers are the most "
                        "relevant passage or past answer, quoted with its source. Nothing is generated.")
            st.caption("To enable written answers and summaries, add GROQ_API_KEY or GEMINI_API_KEY to the .env "
                       "file in the project folder and restart.")
        st.caption(f"Document answers need similarity of at least {DOC_SIM_THRESHOLD:.2f}; "
                   f"ticket answers at least {SIM_THRESHOLD:.2f}.")
    with st.container(key="card-summarize"):
        st.markdown("##### Summarize a document")
        docs = list_documents()
        if not docs:
            st.caption("No documents yet.")
            if st.button("Upload in the Knowledge Hub", icon=":material/upload_file:", width="stretch", key="as-upload"):
                st.switch_page(P["knowledge"])
        else:
            pick = st.selectbox("Document", docs, format_func=lambda d: d["title"], label_visibility="collapsed")
            if st.button("Summarize", icon=":material/summarize:", width="stretch", key="as-summarize"):
                st.session_state["pending_q"] = f"summarize {pick['title']}"
    with st.container(key="card-examples"):
        st.markdown("##### Try asking")
        for i, ex in enumerate(EXAMPLES):
            if st.button(ex, key=f"ex-{i}", width="stretch", type="tertiary"):
                st.session_state["pending_q"] = ex
        if st.button("Clear conversation", icon=":material/delete_sweep:", width="stretch", key="as-clear"):
            clear_history(email)
            st.rerun()

with chat_col:
    msgs = history(email)
    if not msgs:
        ui.empty_state("forum", "Ask your first question",
                       "For example: how do I reset my VPN password, or what was the fix for a checkout 502 error? "
                       "Type “summarize” followed by a document name to get its key points.")
    for m in msgs:
        render(m)

prompt = st.chat_input("Ask a question, or type “summarize” and a document name")
pending = st.session_state.pop("pending_q", None)
q = prompt or pending
if q:
    with chat_col:
        render({"role": "user", "content": q, "meta": {}})
        with st.chat_message("assistant", avatar=":material/auto_awesome:"):
            with st.spinner("Searching your documents and past tickets…"):
                try:
                    answer(q, user_email=email)
                except Exception as e:
                    st.error(f"The assistant hit an error: {e}", icon=":material/error:")
                    st.stop()
    st.rerun()
